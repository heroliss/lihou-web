"""Add public account identity metadata without replacing an existing SQLite file."""
from contextlib import closing
from pathlib import Path
import re
import secrets
import sqlite3
import time

from .public_demo_storage import backup_database


def migrate_account_kinds(database):
    database = Path(database)
    if not database.is_file():
        return
    with closing(sqlite3.connect(database)) as connection:
        tables = {row[0] for row in connection.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        if 'users' not in tables:
            return
        columns = {row[1] for row in connection.execute('PRAGMA table_info(users)')}
        needs_column = 'account_kind' not in columns
        kinds = ({} if needs_column else dict(connection.execute('SELECT id, account_kind FROM users')))
        changes = []
        for uid, username, email in connection.execute('SELECT id, username, email FROM users'):
            if kinds.get(uid, 'account') != 'account':
                continue
            if (re.fullmatch(r'guest_[0-9a-f]{6}', username or '')
                    and re.fullmatch(r'[0-9a-f]{16}@example\.invalid', email or '')):
                changes.append(('guest', uid))
            elif username == 'demo' and email in {'demo@example.com', 'demo@example.invalid'}:
                changes.append(('system', uid))
        if not needs_column and not changes:
            return
        backup = database.parent / ('before-accounts-' + time.strftime('%Y%m%d-%H%M%S')
                                    + '-' + secrets.token_hex(3) + '.sqlite')
        backup_database(database, backup)
        if needs_column:
            connection.execute("ALTER TABLE users ADD COLUMN account_kind VARCHAR(16) NOT NULL DEFAULT 'account'")
        # Only identities generated by the old site are classified as guests.
        # Their persisted kind, rather than a username prefix, controls future access.
        connection.executemany('UPDATE users SET account_kind=? WHERE id=?', changes)
        connection.commit()


def migrate_admin_schema(database):
    """Add moderation metadata once, with an online safety snapshot first.

    New audit/settings tables are created by create_all. Only additive columns
    are applied here because create_all intentionally does not alter old tables.
    """
    database = Path(database)
    if not database.is_file():
        return
    additions = {'users': [('disabled', "BOOLEAN NOT NULL DEFAULT 0"),
                           ('session_version', "INTEGER NOT NULL DEFAULT 0")],
                 'posts': [('hidden', "BOOLEAN NOT NULL DEFAULT 0")]}
    with closing(sqlite3.connect(database)) as connection:
        tables = {row[0] for row in connection.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        pending = []
        for table, fields in additions.items():
            if table not in tables:
                continue
            columns = {row[1] for row in connection.execute(f'PRAGMA table_info({table})')}
            pending.extend((table, name, definition) for name, definition in fields if name not in columns)
        normalize_comments = ('comments' in tables and connection.execute(
            'SELECT 1 FROM comments WHERE disabled IS NULL LIMIT 1').fetchone() is not None)
        if not pending and not normalize_comments:
            return
        backup = database.parent / ('before-admin-' + time.strftime('%Y%m%d-%H%M%S')
                                    + '-' + secrets.token_hex(3) + '.sqlite')
        backup_database(database, backup)
        for table, name, definition in pending:
            connection.execute(f'ALTER TABLE {table} ADD COLUMN {name} {definition}')
        if 'posts' in tables:
            connection.execute('CREATE INDEX IF NOT EXISTS ix_posts_hidden ON posts (hidden)')
        if normalize_comments:
            connection.execute('UPDATE comments SET disabled=0 WHERE disabled IS NULL')
        connection.commit()


def migrate_owner_schema(database):
    """Add owner identity metadata, preserving all old users and their foreign keys."""
    database = Path(database)
    if not database.is_file():
        return
    with closing(sqlite3.connect(database)) as connection:
        tables = {row[0] for row in connection.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        if 'users' not in tables:
            return
        columns = {row[1] for row in connection.execute('PRAGMA table_info(users)')}
        additions = [('is_site_owner', 'BOOLEAN NOT NULL DEFAULT 0'),
                     ('merged_into_id', 'INTEGER REFERENCES users(id)')]
        pending = [(name, definition) for name, definition in additions if name not in columns]
        if not pending:
            return
        backup_database(database, database.parent / ('before-owner-schema-' + time.strftime('%Y%m%d-%H%M%S')
                                                    + '-' + secrets.token_hex(3) + '.sqlite'))
        for name, definition in pending:
            connection.execute(f'ALTER TABLE users ADD COLUMN {name} {definition}')
        connection.commit()
